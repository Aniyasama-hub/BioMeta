# 面向使用者的参数说明，集中维护；不改动算法或输入默认值。
tb_control_help <- function(name, control) {
  explanation <- switch(name,
    min_count = "低表达过滤会排除测到的数量太少、难以稳定比较的基因。默认要求一个基因在至少 3 个样本中原始计数达到 10；两个参数配合使用。调高会保留更少的基因，需重新分析。",
    min_samples = "一个基因至少要在这么多个样本中达到 Count 下限，才进入模型。默认是 3 个样本，请结合每组实际样本数设置；这里统计的是纳入模型的全部样本。",
    alpha = "模型以这个显著性水平优化低表达基因的独立过滤，默认 0.05。它与后面的差异筛选阈值有关但作用不同；调整后需要重新计算模型，完整表仍会保留全部受检基因。",
    pca_top = "PCA 优先使用样本之间变化最大的基因，默认取前 500 个。数量较少时更突出主要变化，数量较多时纳入更多信息；它不会改变用于差异分析的基因范围。",
    pca_scale = "开启后，每个基因的变化会先调整到接近的尺度，再计算 PCA。这样低波动基因也能获得较大权重；开启与关闭回答的侧重点不同，建议比较后再决定。",
    labels = "在图上显示样本名或选定条目的名称，便于追踪具体对象。数据较密时文字可能重叠，可增加画布、减小字号，或只在核对样本时开启。",
    use_batch = "将分组表中的技术批次加入统计模型，尽量区分技术变化与研究条件。批次应在各组之间有交叉；如果一个组完全对应一个批次，模型无法单独判断两者的影响。",
    row_scale = "分别在每一行内比较样本的相对高低，让不同表达水平的基因能共用色尺。开启后颜色不再表示绝对表达量，不能用某行的深色说明它比另一行表达更多。",
    cluster_rows = "把表达模式相似的基因或条目排在附近，帮助寻找共同变化。距离算法决定怎样判断相似，聚类算法决定怎样合并；树形是否显示在图形样式中单独设置。",
    cluster_columns = "按样本之间的相似程度调整列顺序。按组聚类会保留各组的分区，全局聚类允许不同组混在一起；关闭后按输入或既定样本顺序展示。",
    matrix_use_groups = "开启后读取分组表，把样本所属条件用于颜色标记或分区。分组表的样本名必须与矩阵列名完全对应；关闭时只绘制矩阵本身。",
    heatmap_top = "限制本次热图展示多少个候选基因，便于看清文字。差异模式从达到阈值的基因中选取，高变模式按样本间变化选取；它不会把完整分析结果裁成这些行。",
    pathway_top = "限制图中展示的通路条目数量，完整统计表仍会保存。数值越大图会越拥挤，可配合画布高度和名称换行调整；GSEA 中表示最多输出多少条通路曲线。",
    min_set_size = "一个通路与当前数据匹配的基因少于这个数量时，不进入富集检验。太小的基因集容易受个别基因影响；与最大基因集大小一起限制参与分析的通路范围。",
    max_set_size = "一个通路与当前数据匹配的基因多于这个数量时，不进入富集检验。过大的集合可能包含很多宽泛功能，默认上限为 500；调整后需重新分析。",
    panel_trim = "自动裁去图片四周接近白色的区域，数值是允许的颜色偏差百分比。默认 3；调大可能连很浅的图形也裁掉，预览后再决定是否保留。",
    kmeans_k = "指定希望把对象分成几组。组数应少于不同数据点的数量，过大容易把很相似的对象拆开；可结合研究问题和实际分布尝试多个值。",
    kmeans_seed = "固定随机初始化，方便同一数据和参数得到可重复的分组。改变种子可能改变局部最优解，但不会改动输入数值；比较方案时请记录种子。",
    kmeans_scale = "让各数值列先调整到类似尺度，再计算对象的距离。不同指标单位或范围差别大时可考虑开启；关闭时，大范围指标对分组的影响通常更大。",
    beeswarm_log = "用对数纵轴展示跨度很大的数值，便于同时看清高值和低值。所有值必须大于零；坐标刻度发生变化，原始数据不会改写。",
    beeswarm_box = "在单个观测点上叠加箱线图，概括中位数和数据分布。点仍保留每个样本的信息；样本很少时应结合散点判断，不只看箱体。",
    radar_normalize = "把每个指标在当前输入对象中的最小值和最大值映射到统一范围。便于比较不同单位的指标，但加入或删除对象可能改变比例；比较多张图时应保持相同对象集合。",
    NULL)
  if (is.null(explanation)) control else shiny::div(`data-help` = explanation, control)
}
